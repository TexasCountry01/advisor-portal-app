"""
Golden-master pre-publish validation gate (Option A, follow-on to Phase 0's
golden-master regression harness in benefits-software).

Before a ContentBlockVersion is published, this evaluates the block's
display_condition against a fixed set of 24 representative real Fact Finder
Data Contracts — the same 24 cases used by benefits-software's
`php artisan fact-finder:golden-master` HTML regression harness (see
App\\Console\\Commands\\FactFinderGoldenMaster::DEFAULT_CASES there) — and
reports which cases will/won't see the block. This is the "Test against
sample cases" pre-publish safety net described in
docs/FACT_FINDER_PDF_MODERNIZATION_ANALYSIS_2026-09-06.md's "Concrete UI
design" section — the exact safeguard the earlier shelved
feature/pdf-viewer-v2 attempt was missing (per that doc's own retrospective).

The 24 fixture JSON files under golden_master_fixtures/ were generated by
benefits-software/scripts/export_golden_master_contracts.php against the same
24 real employee records as the HTML harness, and are committed here as a
static, durable dataset — no live cross-app HTTP call is needed to run this
gate, avoiding a runtime dependency on benefits-software being reachable.

IMPORTANT: these fixtures are a point-in-time export. If benefits-software's
underlying calculation logic changes in a way that would change these
employees' real Data Contracts, re-run the export script and re-copy the
fixtures here (see docs/FACT_FINDER_PDF_MODERNIZATION_ANALYSIS_2026-09-06.md
for the exact procedure).
"""
import json
from functools import lru_cache
from pathlib import Path

from cases.fact_finder_data_contract import FactFinderDataContractSerializer

from .rules import evaluate_rules

FIXTURES_DIR = Path(__file__).resolve().parent / 'golden_master_fixtures'


@lru_cache(maxsize=1)
def _load_manifest():
    with open(FIXTURES_DIR / 'manifest.json') as f:
        return json.load(f)


@lru_cache(maxsize=1)
def load_golden_master_cases():
    """Load and schema-validate all golden-master Data Contract fixtures once
    (cached for the life of the process — these are static committed files,
    not per-request data). Returns a list of dicts, in manifest order:
    {'emp_id': int, 'label': str, 'contract': <validated nested dict>}.

    Raises RuntimeError if any fixture fails schema validation — committed
    fixtures should always be valid, so a failure here means the schema
    (cases/fact_finder_data_contract.py) and the fixtures have drifted apart
    and must fail loudly rather than silently skip a case.
    """
    manifest = _load_manifest()
    cases = []
    for emp_id_str, label in manifest.items():
        path = FIXTURES_DIR / f'{emp_id_str}.json'
        with open(path) as f:
            raw_contract = json.load(f)

        serializer = FactFinderDataContractSerializer(data=raw_contract)
        if not serializer.is_valid():
            raise RuntimeError(
                f"Golden-master fixture {emp_id_str}.json failed schema validation: {serializer.errors}"
            )
        cases.append({
            'emp_id': int(emp_id_str),
            'label': label,
            'contract': serializer.validated_data,
        })
    return cases


def evaluate_display_condition(display_condition):
    """Evaluate a block's display_condition (the {'rules': [...]} dict stored
    on ContentBlock.display_condition, or None/empty meaning always-shown)
    against every golden-master case.

    Returns a list of dicts in manifest order:
    {'emp_id': int, 'label': str, 'matches': bool, 'error': str or None}.

    A rule-evaluation error (e.g. an unknown operator slipping through,
    which validate_rules() should already prevent) is reported per-case
    rather than raised, so one bad rule doesn't hide results for the other
    23 cases in the UI.
    """
    rules = (display_condition or {}).get('rules', [])
    results = []
    for case in load_golden_master_cases():
        try:
            matches = evaluate_rules(rules, case['contract'])
            error = None
        except ValueError as e:
            matches = False
            error = str(e)
        results.append({
            'emp_id': case['emp_id'],
            'label': case['label'],
            'matches': matches,
            'error': error,
        })
    return results
